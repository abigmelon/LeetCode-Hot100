/* ================================================================
 *                    回溯算法通用模板（C 语言）
 * ================================================================
 * 所有回溯题都是 DFS 在决策树上的遍历，区别只在于：
 *   1. 排列型 or 组合型（选 used[] 还是 start）
 *   2. 在哪记录答案（叶子 / 沿途所有节点）
 *   3. 剪枝条件
 * 拿到题目，对着下面的决策树判断属于哪种，套模板改一行即可。
 * ================================================================ */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

/* ================================================================
 *  类型一：排列型模板
 *  特征：顺序有关 [1,2] ≠ [2,1]    去重靠 used[]
 *  代表题：全排列(46)、全排列II(47)、N皇后(51)
 * ================================================================
 *
 *  决策树示意（nums = [1,2,3]，n! = 6 个叶子）：
 *                     []
 *              /       |       \
 *             1        2        3       ← 从 {1,2,3} 中选 (used 标记)
 *           /   \    /   \    /   \
 *          2     3  1     3  1     2    ← 跳过 used=true 的
 *          |     |  |     |  |     |
 *          3     2  3     1  2     1    ← 叶子 = 答案
 */

void dfs_permute(int* nums, int numsSize, int depth,
                 bool* used, int* path, int** ans, int* idx) {
    // ----- 终止条件：走到叶子（路径长度 == numsSize）-----
    if (depth == numsSize) {
        ans[*idx] = (int*)malloc(sizeof(int) * numsSize);
        memcpy(ans[*idx], path, sizeof(int) * numsSize);
        (*idx)++;
        return;
    }

    // ----- 遍历所有数字，跳过已使用的 -----
    for (int i = 0; i < numsSize; i++) {
        if (used[i]) continue;       // 剪枝：数字已在当前路径中

        used[i] = true;              // 做选择
        path[depth] = nums[i];

        dfs_permute(nums, numsSize, depth + 1, used, path, ans, idx);

        used[i] = false;             // 撤销选择（回溯！）
    }
}


/* ================================================================
 *  类型二：组合/子集型模板
 *  特征：顺序无关 [1,2] = [2,1]    去重靠 start（只往后看）
 *  代表题：子集(78)、子集II(90)、组合(77)、组合总和(39)
 * ================================================================
 *
 *  决策树示意（nums = [1,2,3]，2³ = 8 个节点，每个都是答案）：
 *                     []
 *              /       |       \
 *             1        2        3       ← start=0，选第1个元素
 *           /   \       \
 *          2     3       3              ← start=i+1，只能往后看
 *          |
 *          3                             ← 每个节点都记录！
 */

void dfs_subsets(int* nums, int numsSize, int start, int depth,
                 int* path, int** ans, int* idx, int* colSizes) {
    // ----- 每个节点都是答案，先保存 -----
    colSizes[*idx] = depth;
    ans[*idx] = (int*)malloc(sizeof(int) * depth);
    memcpy(ans[*idx], path, sizeof(int) * depth);
    (*idx)++;

    // ----- 从 start 开始往后选，天然去重 -----
    for (int i = start; i < numsSize; i++) {
        path[depth] = nums[i];       // 做选择

        dfs_subsets(nums, numsSize, i + 1, depth + 1, path, ans, idx, colSizes);

        // path[depth] 会被下一轮循环覆盖，无需显式撤销
    }
}


